import { useState } from 'react'
import { ArrowRight, Film, RefreshCw, Sparkles } from 'lucide-react'
import type { RepurposedShort } from '@shared/brandManual'
import type { Project } from '@shared/types'
import { GulliverMascot } from '../../components/GulliverMascot'
import { Badge, Button, cx } from '../../components/ui'
import { errorText } from '../../lib/format'
import { useApp } from '../../store/app'
import { useProject } from '../../store/project'

export function AutoShortsSection({ project }: { project: Project }) {
  const { toast, go } = useApp()
  const { updateEditor } = useProject()
  const [busy, setBusy] = useState(false)
  const [creatingId, setCreatingId] = useState<string | null>(null)

  const shorts: RepurposedShort[] = project.editor?.autoGeneratedShorts ?? []

  const handleGenerate = async (): Promise<void> => {
    setBusy(true)
    try {
      const res = await window.api.story.repurposeShorts(project.id)
      updateEditor({ autoGeneratedShorts: res })
      toast('success', '3 Varian Shorts berhasil diekstrak!')
    } catch (e) {
      toast('error', errorText(e))
    } finally {
      setBusy(false)
    }
  }

  const handleCreate = async (shortId: string): Promise<void> => {
    setCreatingId(shortId)
    try {
      const b = await window.api.story.createShortProject(project.id, shortId)
      toast('success', 'Proyek Shorts 9:16 dibuat!')
      go({ name: 'project', id: b.project.id })
    } catch (e) {
      toast('error', errorText(e))
    } finally {
      setCreatingId(null)
    }
  }

  return (
    <section className="flex flex-col gap-3 rounded-2xl border-[1.5px] border-line bg-surface p-4 shadow-sm">
      <div className="flex items-center justify-between border-b border-line pb-2.5">
        <div className="flex items-center gap-2">
          <Film className="size-4 text-accent-dark" />
          <h2 className="font-display text-base font-bold">Auto-Repurposed Shorts (1 Long = 3 Shorts)</h2>
          <Badge tone="ok">3 Varian 9:16</Badge>
        </div>
        <Button
          variant="secondary"
          size="sm"
          icon={<RefreshCw className={cx('size-3.5', busy && 'animate-spin')} />}
          loading={busy}
          onClick={() => void handleGenerate()}
        >
          {shorts.length ? 'Regenerasi Shorts' : 'Ekstrak 3 Shorts'}
        </Button>
      </div>

      <p className="text-xs text-ink-2">
        Sesuai <strong>SSOT The Economic Everyday Empire</strong>: Video Long diekstrak jadi 3 Shorts (0–4s Hook, 4–35s Meat, 35–48s Bridge + Loop).
      </p>

      {shorts.length === 0 ? (
        <div className="flex flex-col items-center justify-center gap-2 py-6 text-center rounded-xl bg-sand/40 border border-dashed border-line">
          <Sparkles className="size-6 text-accent-dark" />
          <p className="text-xs font-semibold text-ink">Belum ada Shorts diekstrak</p>
          <Button variant="accent" size="sm" onClick={() => void handleGenerate()} loading={busy}>
            Ekstrak 3 Shorts Sekarang
          </Button>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-3 gap-3 pt-1">
          {shorts.map((s, idx) => (
            <div key={s.shortId || idx} className="flex flex-col justify-between rounded-xl border border-line bg-paper p-3 shadow-sm">
              <div className="flex flex-col gap-2">
                <div className="flex items-start justify-between gap-1.5">
                  <Badge tone={idx === 1 ? 'warn' : 'info'}>Short #{idx + 1}</Badge>
                  <span className="text-[11px] font-mono text-ink-2">{s.targetDurationSec}s · 9:16</span>
                </div>
                <h3 className="font-bold text-xs text-ink leading-tight">{s.title}</h3>
                <div className="flex flex-col gap-1.5 pt-1 border-t border-dashed border-line">
                  {s.segments.map((seg, sIdx) => (
                    <div key={sIdx} className="rounded-lg bg-surface p-1.5 border border-line-2 flex flex-col gap-0.5 text-xs">
                      <span className="font-semibold text-[9px] text-accent font-mono uppercase">{seg.phase.replace(/_/g, ' ')}</span>
                      <p className="text-ink-2 line-clamp-2 text-[11px] leading-snug">{seg.narrationText}</p>
                      {seg.diegeticText && (
                        <div className="font-mono text-[9px] bg-sand px-1.5 py-0.5 rounded text-ink font-semibold truncate">
                          [DIEGETIC]: {seg.diegeticText}
                        </div>
                      )}
                    </div>
                  ))}
                </div>
              </div>
              <div className="pt-2 border-t border-line mt-2 flex items-center justify-between">
                <GulliverMascot width={36} height={40} pose={s.segments[0]?.gulliverState?.pose ?? 'saluting'} />
                <Button variant="primary" size="sm" loading={creatingId === s.shortId} icon={<ArrowRight className="size-3.5" />} onClick={() => void handleCreate(s.shortId)}>
                  Buka Proyek (9:16)
                </Button>
              </div>
            </div>
          ))}
        </div>
      )}
    </section>
  )
}
